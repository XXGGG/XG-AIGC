/* 网站显示的写法 */
export function libPrompt(id,v,m){
  if(id==="mimic")return MIMIC_PROMPT;
  if(id==="fromchar"){
    if(m==="gpt")return gpt("keep","角色设定图",null,v==="s1"?LFULL("后脑的发型"):v==="s3"?LTRI("后脑的发型"):L3);
    return dsSheet(v);
  }
  const p=P[id];if(!p)return "";
  if(m==="gpt")return v==="pose"?gptPose(p.style,id==="outfit"?OUTFIT:null):gpt(p.style,p.style==="keep"?"角色设定图":p.task,id==="outfit"?OUTFIT:null,v==="sheet"?LFULL("后脑的发型"):v==="sheet3"?LTRI("后脑的发型",p.style==="chibi"):L3);
  return v==="pose"?posePrompt(id):afterPrompt(id,v);
}
