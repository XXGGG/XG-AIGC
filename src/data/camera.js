/* 高亮颜色和筛选按钮一一对应（10-27 用户定）：每组的段落名和说明用该组的颜色；
   景别标签跟「镜头」组同色（蓝），视角用相近的青色；人物动作不标 */
export const CAM_TONE={move:"detail",rig:"rig",shot:"person",size:"person",angle:"angle",speed:"hair",optics:"wear",trans:"shoes",look:"look"};
const SECT={"【运镜】":"move","【镜头】":"shot","【速度】":"speed","【对焦】":"optics","【光线】":"optics","【转场】":"trans","【画风】":"look"};
export function camSegs(txt,cat){
  const out=[];let sec=null;
  txt.split("\n").forEach((ln,i)=>{
    if(i)out.push({t:"\n"});
    if(ln.startsWith("【"))sec=SECT[ln]||null;
    if(ln.startsWith("运镜：")){out.push({t:ln,m:"move"});return}
    if(sec&&ln){out.push({t:ln,m:sec});return}
    /* 时间段后面跟【景别】【视角】，只有一个标签时算景别 */
    const m=ln.match(/^(【[0-9.]+—[0-9.]+ 秒】)(【[^】]+】)(【[^】]+】)?(.*)$/);
    if(m){out.push({t:m[1]},{t:m[2],m:"size"});if(m[3])out.push({t:m[3],m:"angle"});if(m[4])out.push({t:m[4]});return}
    out.push({t:ln});
  });
  if(cat==="rig")out.forEach(g=>{if(g.m==="move")g.m="rig"});
  return out;
}
